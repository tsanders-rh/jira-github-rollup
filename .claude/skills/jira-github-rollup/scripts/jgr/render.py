"""Assemble the complete rollup in GitHub-flavored Markdown.

The LLM supplies the judgements - the summary, each coverage assessment and
what it rests on, the gaps, caveats and risks. Everything structural is built
here: section order, tables, counts, percentages, the trend section, the
status line, the marker line, and the partial shape used when no epic is
mapped.

The report is always complete. Reused assessments are rendered identically to
freshly made ones; nothing anywhere emits "unchanged since last run" in place
of a row.
"""

from __future__ import annotations

from . import clauses as clauses_mod
from . import links as links_mod
from . import metrics as metrics_mod
from . import outcomes as outcomes_mod
from . import scope as scope_mod
from . import summary as summary_mod
from . import util

TYPE_LABEL = {
    "AC": ("acceptance criterion", "acceptance criteria"),
    "SC": ("success criterion", "success criteria"),
    "DoD": ("definition-of-done item", "definition-of-done items"),
    "REQ": ("unlabelled requirement", "unlabelled requirements"),
}
TYPE_ORDER = ["AC", "SC", "DoD", "REQ"]
MINUS = "−"
EMDASH = "—"
WORDS = [
    "no", "one", "two", "three", "four", "five", "six",
    "seven", "eight", "nine", "ten", "eleven", "twelve",
]

MARKER = "Generated by the jira-github-rollup skill"
LABEL = (
    "_Unweighted counts of requirements and child issues. Not a measure of effort\n"
    "completed, work remaining, or release readiness._"
)


def spell(count):
    return WORDS[count] if 0 <= count < len(WORDS) else str(count)


def cell(text):
    """Make a string safe for a Markdown table cell."""
    if text is None:
        return EMDASH
    return " ".join(str(text).split()).replace("|", "\\|")


def signed(value, unit_singular, unit_plural=None):
    word = unit_singular if abs(value) == 1 else (unit_plural or unit_singular + "s")
    sign = "+" if value >= 0 else MINUS
    return f"{sign}{abs(value)} {word}"


def signed_pp(value):
    sign = "+" if value >= 0 else MINUS
    return f"{sign}{abs(value)} pp"


def type_counts(requirements):
    counts = {}
    for requirement in requirements:
        counts[requirement.get("type") or "REQ"] = counts.get(requirement.get("type") or "REQ", 0) + 1
    return counts


def describe_mix(counts):
    parts = []
    for key in TYPE_ORDER:
        if counts.get(key):
            singular, plural = TYPE_LABEL[key]
            parts.append(f"{counts[key]} {singular if counts[key] == 1 else plural}")
    for key in sorted(set(counts) - set(TYPE_ORDER)):
        parts.append(f"{counts[key]} {key}")
    return ", ".join(parts) if parts else "no requirements"


# --- fragments -----------------------------------------------------------


def format_pr(pr):
    ref = links_mod.link(pr.get("ref"), "pr")
    state = (pr.get("state") or "unknown").lower()
    if state == "merged":
        return f"{ref} (merged {util.date_only(pr.get('mergedAt'))})"
    if state == "closed":
        closed = pr.get("closedAt") or pr.get("updatedAt")
        return f"{ref} (closed unmerged{' ' + util.date_only(closed) if closed else ''})"
    if state == "draft":
        return f"{ref} (draft)"
    if state == "open":
        age = util.days_between(util.iso(util.utcnow()), pr.get("createdAt") or pr.get("updatedAt"))
        return f"{ref} (open{f', {age}d' if age is not None else ''})"
    return f"{ref} ({state})"


def child_status(child):
    if child.get("accessible") is False:
        return "Not readable"
    state = (child.get("state") or "").upper()
    reason = (child.get("stateReason") or "").upper()
    if state == "CLOSED":
        if reason == "COMPLETED":
            return "Closed (completed)"
        if reason == "NOT_PLANNED":
            return "Closed (not planned)"
        return "Closed (reason not recorded)"
    if reason == "REOPENED":
        return "Open (reopened)"
    return "Open"


def format_evidence(evidence):
    """Evidence refs as clickable links wherever a ref resolves to a URL.

    A check or job name is not a ref and gets no link; `links.link` returns it
    as written rather than guessing a URL for it.
    """
    if not evidence:
        return EMDASH
    parts = []
    for item in evidence:
        ref = item.get("ref")
        kind = (item.get("kind") or "").lower()
        when = item.get("at")
        state = (item.get("state") or "").lower()
        if kind == "pr":
            suffix = f" ({state} {util.date_only(when)})" if when else (f" ({state})" if state else "")
            parts.append(links_mod.link(ref, "pr", f"PR {ref}") + suffix)
        elif kind in ("check", "test"):
            parts.append(f"{ref}{f' ({state})' if state else ''}")
        else:
            parts.append(links_mod.link(ref))
    return ", ".join(parts)


def criterion_label(requirement, site=None):
    """`SC1 (RHOAIENG-1234)`, linked to the parent issue when a site is known.

    Criteria have no anchor of their own, so the id travels in the link text.
    """
    key = requirement.get("sourceKey")
    text = f"{requirement.get('id')} ({key})" if key else str(requirement.get("id"))
    url = links_mod.jira_url(site, key)
    return f"[{text}]({url})" if url else text


# --- sections ------------------------------------------------------------


def derive_status(assembly, computed):
    manifest = assembly["manifest"]
    if not manifest.get("observed", bool(manifest.get("epics"))):
        return "Unknown " + EMDASH + " " + scope_mod.status(manifest.get("unobservedKind"))
    if assembly.get("blocked"):
        return "Blocked"

    requirements = assembly["requirements"]
    children = manifest.get("children") or []
    coverage = computed["coverage"]["buckets"]
    downstream = computed["downstream"]["buckets"]
    all_covered = requirements and coverage["Evidence found"] == len(requirements)
    none_outstanding = downstream["pending"] == 0 and downstream["unknown"] == 0
    all_children_done = children and all(
        (child.get("state") or "").upper() == "CLOSED" for child in children
    )
    if all_covered and none_outstanding and all_children_done:
        return "Complete"

    has_pr = any(pr for child in children for pr in child.get("prs") or [])
    merged = any(
        (pr.get("state") or "") == "merged" for child in children for pr in child.get("prs") or []
    )
    if merged or any((child.get("state") or "").upper() == "CLOSED" for child in children):
        return "In progress"
    if has_pr:
        return "In progress, early"
    if children:
        return "Not started"
    return "In progress"


def header(assembly, computed):
    jira = assembly["jira"]
    lines = ["### Upstream Development Rollup", ""]
    lines.append(f"**Status:** {derive_status(assembly, computed)}")
    mappings = assembly.get("mappings") or []
    if mappings:
        for mapping in mappings:
            label = f"[{mapping['ref']}]({mapping['url']})" if mapping.get("url") else mapping["ref"]
            title = f" {EMDASH} {mapping['title']}" if mapping.get("title") else ""
            note = ""
            if (mapping.get("linkSource") or "").startswith("incidental"):
                note = " (from an unlabelled URL on the Jira; confirm this is the intended mapping)"
            lines.append(f"**Source epic:** {label}{title}{note}")
    else:
        lines.append(f"**Source epic:** none recorded on {jira['key']}")
    lines.append(f"**Generated:** {util.date_only(assembly['generatedAt'])}")
    return lines


def progress_section(assembly):
    manifest = assembly["manifest"]
    children = manifest.get("children") or []
    if not manifest.get("observed", bool(manifest.get("epics"))):
        return []

    buckets = metrics_mod.child_metrics(children)["buckets"]
    merged_prs = sum(
        1 for child in children for pr in child.get("prs") or [] if (pr.get("state") or "") == "merged"
    )
    counts = f"{buckets['completed']} of {len(children)} child issues closed as completed"
    if buckets["notPlanned"]:
        counts += f"; {buckets['notPlanned']} closed as not planned"
    if buckets["noReasonRecorded"]:
        counts += f"; {buckets['noReasonRecorded']} closed with no reason recorded"
    if buckets["unreadable"]:
        counts += f"; {buckets['unreadable']} not readable"
    counts += "."

    lines = ["#### Progress", "", counts]
    if merged_prs:
        # On its own line, with what it does not mean. Sitting next to the
        # issue ratio it reads as a second progress measure, and a merged pull
        # request is evidence that code landed, not that a criterion is met.
        lines.extend(
            [
                "",
                f"{util.pluralize(merged_prs, 'pull request')} merged across the traversed "
                "children. Pull-request volume is not a measure of criteria met; the "
                "assessment is per criterion below.",
            ]
        )
    lines.append("")

    if len(children) == 0:
        lines.append(
            "The linked epic was read and has no child issues in the reachable set."
        )
        return lines
    if len(children) > 15:
        by_repo = {}
        for child in children:
            by_repo.setdefault(child["ref"].split("#")[0], []).append(child)
        lines.append(f"{len(children)} children across {len(by_repo)} repositories.")
        for repo in sorted(by_repo):
            group = by_repo[repo]
            open_or_flagged = [
                child
                for child in group
                if (child.get("state") or "").upper() != "CLOSED"
                or (child.get("stateReason") or "").upper() != "COMPLETED"
            ]
            done = len(group) - len(open_or_flagged)
            lines.append("")
            lines.append(f"**{repo}** {EMDASH} {done} of {len(group)} closed as completed.")
            if open_or_flagged:
                lines.append("")
            # One line per outstanding child, not a comma-run. The full
            # inventory belongs in the detailed assessment, but a 20-ref
            # paragraph is not an inventory anyone can read or click.
            for child in open_or_flagged:
                title = f" {EMDASH} {child['title']}" if child.get("title") else ""
                lines.append(
                    f"- {links_mod.link(child['ref'], label=links_mod.short(child['ref']))} "
                    f"({child_status(child).lower()}){title}"
                )
        return lines

    lines.extend(["| Child | Status | PRs |", "| --- | --- | --- |"])
    for child in children:
        title = f" {EMDASH} {child['title']}" if child.get("title") else ""
        linked = links_mod.link(child["ref"]) + cell(title)
        prs = ", ".join(format_pr(pr) for pr in child.get("prs") or []) or EMDASH
        lines.append(f"| {linked} | {cell(child_status(child))} | {prs} |")
    return lines


def jira_scope_section(assembly):
    jira = assembly["jira"]
    fix = ", ".join(jira.get("fixVersions") or []) or "none"
    lines = [
        "#### Jira scope",
        "",
        f"{jira['key']} {EMDASH} {jira.get('summary', '')} ({jira.get('status', 'unknown status')}, fix version {fix})",
    ]
    children = jira.get("children") or []
    if children:
        listed = "; ".join(
            f"{child['key']} {EMDASH} {child.get('summary', '')} ({child.get('status', 'unknown')})"
            for child in children
        )
        lines.append(f"Child requirements read: {listed}")
    return lines


def outcome_table(tallied):
    """The four counts, identical in every rendering and taken from one tally."""
    counts = tallied["counts"]
    return [
        "| " + " | ".join(outcomes_mod.LABELS[name] for name in outcomes_mod.OUTCOMES) + " |",
        "| " + " | ".join("---" for _ in outcomes_mod.OUTCOMES) + " |",
        "| " + " | ".join(str(counts[name]) for name in outcomes_mod.OUTCOMES) + " |",
    ]


def type_breakdown(requirements):
    """The same outcomes split by requirement type, with no combined score.

    Acceptance criteria, success criteria and definition-of-done items answer
    different questions, and the pooled table above hides which kind is
    lagging: eight met acceptance criteria and zero met success criteria is a
    different situation from the reverse, and both read as "8 of 16". There is
    deliberately no total column and no percentage - dividing across the types
    would produce a feature-completion number, which none of these measure.
    """
    groups = metrics_mod.by_type(requirements)
    if len(groups) < 2:
        return []
    header_cells = ["Type", "Total"] + [outcomes_mod.LABELS[n] for n in outcomes_mod.OUTCOMES]
    lines = [
        "",
        "| " + " | ".join(header_cells) + " |",
        "| " + " | ".join("---" for _ in header_cells) + " |",
    ]
    for group in groups:
        singular, plural = TYPE_LABEL.get(group["type"], (group["type"], group["type"]))
        name = singular if group["total"] == 1 else plural
        lines.append(
            "| {} | {} | {} |".format(
                cell(name.capitalize()),
                group["total"],
                " | ".join(str(group["outcomes"][n]) for n in outcomes_mod.OUTCOMES),
            )
        )
    lines.append("")
    lines.append(
        "_Counted separately by type. They are not summed into a completion figure: an "
        "acceptance criterion, a success criterion and a definition-of-done item are not "
        "interchangeable units of delivery._"
    )
    return lines


def coverage_section(assembly, computed, tallied=None):
    requirements = assembly["requirements"]
    site = (assembly.get("jira") or {}).get("site")
    lines = ["#### Requirements coverage", ""]
    if not requirements:
        sources = ", ".join(assembly.get("requirementSourcesChecked") or ["description", "sub-tasks"])
        lines.append(
            f"No acceptance criteria, success criteria, or definition of done found on "
            f"{assembly['jira']['key']} ({sources}). Nothing to assess coverage against."
        )
        return lines

    lines.append(describe_mix(type_counts(requirements)) + ".")
    tallied = tallied or outcomes_mod.tally(requirements)
    lines.append("")
    lines.extend(outcome_table(tallied))
    lines.append("")
    lines.append(
        f"_{tallied['caption']} {tallied['total']} criteria in total; the four columns are "
        "mutually exclusive and sum to that. These are the same counts the Jira summary "
        "carries._"
    )
    lines.extend(type_breakdown(requirements))
    lines.append("")
    lines.extend(
        [
            "| Requirement | Outcome | Evidence | Evidence state | Coverage | Gap / next validation step |",
            "| --- | --- | --- | --- | --- | --- |",
        ]
    )

    collapsible = [
        requirement
        for requirement in requirements
        if requirement.get("assessment") == "Evidence found"
        and not requirement.get("unresolvedClauses")
        and not requirement.get("uncoveredClauses")
        and ((requirement.get("downstream") or {}).get("state") == "confirmed")
    ]
    collapse = len(requirements) > 12 and len(collapsible) > 1
    shown = [r for r in requirements if not (collapse and r in collapsible)]

    for requirement in shown:
        label = criterion_label(requirement, site) + f' "{cell(requirement.get("text", ""))}"'
        coverage = requirement.get("assessment") or "Unable to assess"
        detail = requirement.get("coverageDetail")
        if detail:
            coverage = f"{coverage} {EMDASH} {detail}"
        lines.append(
            "| {} | {} | {} | {} | {} | {} |".format(
                label,
                outcomes_mod.ROW_LABELS[outcomes_mod.classify(requirement)],
                format_evidence(requirement.get("evidence")),
                cell(requirement.get("evidenceState") or EMDASH),
                cell(coverage),
                cell(requirement.get("gap") or EMDASH),
            )
        )
    if collapse:
        # Qualified, because the collapsed list is the one place a reader gets
        # ids without the row that says which Jira issue they came from, and
        # `AC1` on its own belongs to five issues in a multi-issue rollup.
        ids = ", ".join(summary_mod.qualified(r) for r in collapsible)
        lines.append("")
        lines.append(
            f"{len(collapsible)} further requirements assessed Evidence found with no "
            f"downstream step outstanding: {ids}."
        )
    return lines


def downstream_section(assembly):
    manifest = assembly["manifest"]
    if not manifest.get("observed", bool(manifest.get("epics"))):
        return []
    requirements = assembly["requirements"]
    listed = [
        requirement
        for requirement in requirements
        if (requirement.get("downstream") or {}).get("detail")
        and (requirement.get("evidenceState") in ("merged", "tested")
             or (requirement.get("downstream") or {}).get("state") in ("pending", "confirmed"))
    ]
    if not listed:
        return []
    site = (assembly.get("jira") or {}).get("site")
    lines = ["#### Downstream qualification", ""]
    lines.extend(downstream_states(requirements))
    lines.append("")
    for requirement in listed:
        state = ((requirement.get("downstream") or {}).get("state") or "unknown").lower()
        lines.append(
            f"- {criterion_label(requirement, site)} {EMDASH} "
            f"**{metrics_mod.DOWNSTREAM_LABELS.get(state, metrics_mod.DOWNSTREAM_LABELS['unknown'])}.** "
            f"{links_mod.linkify((requirement.get('downstream') or {}).get('detail'))}"
        )
    if len(listed) < len(requirements):
        lines.extend(
            [
                "",
                "Requirements not listed above have no identified downstream step in the sources",
                "inspected; that is not confirmation that none is required.",
            ]
        )
    return lines


def downstream_states(requirements):
    """How far qualification got, in three states that are not interchangeable.

    Upstream coverage and release readiness are separate questions and this
    table only answers part of the second one. The distinction worth protecting
    is between "not inspected" and "inspected, nothing found": the first is an
    open question, the second is a negative result, and a reader who reads one
    as the other either over- or under-states what is known.
    """
    counts = {name: 0 for name in metrics_mod.DOWNSTREAM}
    for requirement in requirements or []:
        state = ((requirement.get("downstream") or {}).get("state") or "unknown").lower()
        counts[state if state in counts else "unknown"] += 1
    lines = [
        "| Qualification | Criteria |",
        "| --- | --- |",
    ]
    for state in metrics_mod.DOWNSTREAM:
        lines.append(f"| {metrics_mod.DOWNSTREAM_LABELS[state]} | {counts[state]} |")
    lines.append("")
    lines.append(
        "_Qualification is a separate question from upstream coverage, and neither is a "
        "release-readiness verdict. A criterion with upstream evidence and no qualification "
        "is not partly released._"
    )
    return lines


def dependencies_section(assembly):
    """Decisions, blockers, and tracking clarifications, each with a pointer.

    The wording for an unowned criterion is deliberate. "Identify and link the
    work covering SC6" is a request; "the Metering epic covers SC6" is a claim
    about an epic nobody traversed. The skill is allowed to make the first and
    never the second, so the renderer only ever produces the first - a named
    dependency has to arrive in `dependencies`, from a source that was read.
    """
    requirements = assembly.get("requirements") or []
    site = (assembly.get("jira") or {}).get("site")
    key = (assembly.get("jira") or {}).get("key")
    lines = []

    def _clause_text(clause):
        """A clause, terminated, so the sentence after it does not run on.

        The model writes these as fragments as often as sentences, and both
        are reasonable; only the renderer knows another sentence follows.
        """
        text = (clause if isinstance(clause, str) else (clause or {}).get("text", "")).strip()
        return text if text.endswith((".", "!", "?", ";", ":")) else text + "."

    decisions = [r for r in requirements if r.get("unresolvedClauses")]
    for requirement in decisions:
        for clause in requirement["unresolvedClauses"]:
            lines.append(
                f"- **Decision needed** {EMDASH} {criterion_label(requirement, site)}: "
                f"{_clause_text(clause)} "
                "Until it is recorded, this clause is unassessable rather than unmet."
            )

    # A clause nobody has evidence for is a different ask from a clause nobody
    # has decided, and it is three different asks among themselves. Grouped by
    # kind and labelled with it, because the reader's next move is entirely
    # determined by which one it is: fix the code, find the work, or get
    # access. "Clause not covered" sent all three to the same place.
    grouped = clauses_mod.by_kind(requirements)
    for kind in clauses_mod.ORDER:
        for requirement, clause in grouped[kind]:
            detail = [
                f"- **{clauses_mod.LABELS[kind]}** {EMDASH} {criterion_label(requirement, site)}: "
                f"{_clause_text(clause)} {clauses_mod.MEANS[kind].capitalize()}"
            ]
            if clause["kind"] == "implementation-gap" and clause["evidence"]:
                detail.append(f", shown by {_join_clauses(clause['evidence'])}")
            elif clause["kind"] == "evidence-gap" and clause["inspected"]:
                detail.append(f", having inspected {_join_clauses(clause['inspected'])}")
            elif clause["kind"] == "inspection-limitation":
                detail.append(f": {clause['limitation'].rstrip('.')}")
            # The revision is part of the finding, not a footnote. A read of
            # the default branch and a read of the merge commit are different
            # reads, and only one of them is about the evidence in the table.
            if clause["revision"]:
                detail.append(f" (at {clause['revision']})")
            detail.append(f". Next: {_clause_text(clause['nextAction'] or '')}")
            lines.append("".join(detail))

    unowned = [
        r
        for r in requirements
        if outcomes_mod.classify(r) == "unverified" and not r.get("evidence")
    ]
    for requirement in unowned:
        lines.append(
            f"- **Tracking clarification** {EMDASH} no upstream work in the traversed set maps "
            f"to {criterion_label(requirement, site)}. Identify and link the work covering "
            # The criterion's own source key, not the rollup's. In a rollup
            # over several Jira issues these differ, and naming the parent
            # sends the reader to the wrong issue to find an `AC1` that five
            # of them have.
            f"{summary_mod.qualified(requirement)}"
            + ". Absence in the sources inspected is not a finding that the work does not exist."
        )

    # Dependencies named by a source that was actually read - a linked Jira, a
    # dependency reference in an issue body. Never inferred from a gap.
    for dependency in assembly.get("dependencies") or []:
        pointer = dependency.get("ref") or dependency.get("key")
        label = (
            links_mod.link(pointer)
            if links_mod.url_for(pointer)
            else links_mod.jira_link(pointer, site)
            if pointer
            else "no owning ticket identified"
        )
        criteria = ", ".join(dependency.get("criteria") or []) or "unstated criteria"
        lines.append(
            f"- **Dependency** {EMDASH} {criteria}: {label}. "
            f"{dependency.get('note') or 'Named on a source that was read; not traversed by this run.'}"
        )

    if not lines:
        return []
    return ["#### Dependencies, decisions, and tracking gaps", ""] + lines


def scope_section(assembly):
    """What this run looked at, and what it could not.

    Everything here used to depend on the model copying it out of the manifest
    by hand. It is all mechanical, it is all in the manifest, and leaving it to
    prose meant four untraversed nested epics could vanish from a report that
    otherwise read as complete.
    """
    manifest = assembly.get("manifest") or {}
    children = manifest.get("children") or []
    epics = manifest.get("epics") or []
    lines = ["#### Collection scope and limitations", ""]

    sources = ", ".join(assembly.get("requirementSourcesChecked") or ["description", "sub-tasks"])
    lines.append(f"- Jira sources read for requirements: {sources}.")

    if not manifest.get("observed", bool(epics)):
        lines.append(
            f"- No upstream epic was read ({manifest.get('unobservedReason') or 'reason not recorded'}). "
            "Upstream coverage is unassessable, not absent."
        )
    else:
        repos = len({child["ref"].split("#")[0] for child in children})
        lines.append(
            f"- Traversed {util.pluralize(len(epics), 'epic')}, "
            f"{util.pluralize(len(children), 'child issue')} across "
            f"{util.pluralize(repos, 'repository', 'repositories')}."
        )

    # Untraversed branches first, and named individually. A note saying a
    # nested epic was traversed and a note saying one was not used to be
    # rendered under the same "Not traversed:" prefix, which made the
    # limitation unreadable precisely where it mattered most.
    untraversed = manifest.get("untraversed") or []
    for entry in untraversed:
        title = f" {EMDASH} {cell(entry.get('title'))}" if entry.get("title") else ""
        reason = entry.get("reason") or "no reason recorded"
        # The mention reason already names the relation it came in on; the
        # depth-cap reason does not. Stating it twice in one sentence reads as
        # two separate facts, which is how a reader stops trusting the line.
        via = entry.get("discoveredVia")
        seen = f", reached by {via}" if via and via not in reason else ""
        lines.append(
            f"- **Not traversed:** {links_mod.link(entry.get('ref'))}{title}. Identified as a "
            f"nested epic ({entry.get('nestedVia')}){seen}; {reason}."
        )
    if untraversed:
        lines.append(
            "- Criteria owned by work beneath the epics above are not in this assessment at "
            "all. Any row below reading as unevidenced may be covered there: that is a limit "
            "of the traversal, not a finding about the work."
        )
    for note in manifest.get("traversalNotes") or []:
        lines.append(f"- Traversal: {links_mod.linkify(note)}")

    unreadable = [entry for entry in manifest.get("access") or [] if entry.get("status") != "readable"]
    for entry in unreadable:
        lines.append(
            f"- Not readable: {entry.get('ref')} ({entry.get('status')}) {EMDASH} "
            f"{entry.get('detail') or 'no detail recorded'}."
        )

    other = manifest.get("dependencies") or []
    if other:
        refs = ", ".join(
            links_mod.link(item["ref"] if isinstance(item, dict) else item)
            for item in other
            if (item.get("ref") if isinstance(item, dict) else item)
        )
        lines.append(f"- Also inspected outside the epic tree: {refs}.")

    if not manifest.get("traversalComplete", True):
        lines.append(
            "- Traversal did not complete. Counts below the epic are a floor, not a total."
        )

    lines.append(
        "- Evidence basis: issue and pull-request metadata, changed-file lists, and CI "
        "check results from the cached responses. No diffs were read, so a changed file "
        "or a passing job locates the work; it does not by itself verify a behaviour."
    )
    # Named individually, with the revision each was read at. A follow-up read
    # is the one place this report quotes source, and a claim resting on one
    # is only checkable if the reader can open the same file at the same
    # commit. "We also read some code" is not that.
    reads = assembly.get("sourceReads") or []
    if reads:
        lines.append(
            f"- {util.pluralize(len(reads), 'source file')} read as a bounded follow-up, "
            f"at the {'revision' if len(reads) == 1 else 'revisions'} named: "
            f"{', '.join(f'`{ref}`' for ref in reads)}."
        )

    # The one statement a reader must not have to infer. A criterion whose
    # clause could not be inspected looks, in the table, exactly like one that
    # was inspected and came back empty.
    unfinished = clauses_mod.incomplete(assembly.get("requirements") or [])
    if unfinished:
        labels = ", ".join(summary_mod.qualified(r) for r in unfinished)
        lines.append(
            f"- **This investigation is incomplete.** "
            f"{util.pluralize(len(unfinished), 'criterion', 'criteria').capitalize()} "
            f"{'carries' if len(unfinished) == 1 else 'carry'} a clause that could not be "
            f"inspected: {labels}. Each names the constraint above. The position on those "
            "clauses is unresolved, not negative."
        )

    lines.append(
        "- No downstream build, payload, or qualification run was inspected. Downstream "
        "state is `unknown` unless a source that was read says otherwise."
    )
    return lines


def bullet_section(title, items):
    if not items:
        return []
    lines = [f"#### {title}", ""]
    lines.extend(f"- {item}" for item in items)
    return lines


def needed_section(assembly):
    key = assembly["jira"]["key"]
    manifest = assembly.get("manifest") or {}
    kind = manifest.get("unobservedKind")
    refs = [epic["ref"] for epic in manifest.get("epics") or [] if epic.get("ref")]
    return [
        "#### What is needed to complete this assessment",
        "",
    ] + scope_mod.needed(kind, key, refs)


