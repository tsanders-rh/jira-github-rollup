def _change_cell(delta, unit_singular, unit_plural=None):
    kind = delta["kind"]
    if kind in ("no-change",):
        return "no change"
    if kind == "moved":
        return f"{signed(delta['count'], unit_singular, unit_plural)}, {signed_pp(delta['pp'])}"
    return delta.get("text", EMDASH)


def _bucket_row(label, previous, current, keys):
    def render(buckets):
        return " / ".join(str((buckets or {}).get(key, 0)) for key in keys)

    before = render(previous)
    after = render(current)
    change = metrics_mod.bucket_delta(previous, current, keys)
    if set(change.split(" / ")) == {"0"}:
        change = "no change"
    return f"| {label} | {before} | {after} | {change} |"


def trend_section(assembly, computed):
    diff = assembly.get("diff") or {}
    baseline = diff.get("baseline")
    problem = diff.get("baselineProblem")
    lines = ["#### Trend since previous snapshot", ""]

    if not baseline:
        if problem:
            lines.append(
                f"A snapshot dated {util.date_only(problem.get('generatedAt'))} exists but could not "
                f"be read ({problem.get('detail')}). Baseline established {EMDASH} no comparison is made."
            )
        else:
            lines.append(f"Baseline established {EMDASH} no prior snapshot available.")
        return lines

    baseline_snapshot = assembly.get("baselineSnapshot") or {}
    previous = metrics_mod.from_snapshot(baseline_snapshot) if baseline_snapshot else None
    kind = "published" if baseline.get("publication") == "published" else "draft"
    suffix = "" if kind == "published" else " (never published)"
    lines.append(
        f"Baseline: {kind} snapshot {util.date_only(baseline.get('generatedAt'))}{suffix}. "
        f"This snapshot: {util.date_only(assembly['generatedAt'])}."
    )
    lines.append("")
    lines.extend(["| Indicator | Previous | Current | Change |", "| --- | --- | --- | --- |"])

    child_delta = metrics_mod.delta(previous["children"] if previous else None, computed["children"])
    lines.append(
        "| Child issues completed | {} | {} | {} |".format(
            metrics_mod.render_ratio(previous["children"]) if previous else EMDASH,
            metrics_mod.render_ratio(computed["children"]),
            _change_cell(child_delta, "issue"),
        )
    )
    coverage_delta = metrics_mod.delta(previous["coverage"] if previous else None, computed["coverage"])
    lines.append(
        "| Requirements with evidence found | {} | {} | {} |".format(
            metrics_mod.render_ratio(previous["coverage"]) if previous else EMDASH,
            metrics_mod.render_ratio(computed["coverage"]),
            _change_cell(coverage_delta, "requirement"),
        )
    )
    lines.append(
        _bucket_row(
            "Partial / no evidence / unable to assess",
            (previous["coverage"]["buckets"] if previous else {}),
            computed["coverage"]["buckets"],
            ["Partial evidence", "No evidence found", "Unable to assess"],
        )
    )
    lines.append(
        _bucket_row(
            "Downstream confirmed / pending / unknown",
            (previous["downstream"]["buckets"] if previous else {}),
            computed["downstream"]["buckets"],
            ["confirmed", "pending", "unknown"],
        )
    )

    buckets = computed["children"]["buckets"]
    manifest = assembly["manifest"]
    if buckets["notPlanned"] or buckets["noReasonRecorded"]:
        refs_not_planned = [
            child["ref"]
            for child in manifest.get("children") or []
            if (child.get("stateReason") or "").upper() == "NOT_PLANNED"
        ]
        refs_no_reason = [
            child["ref"]
            for child in manifest.get("children") or []
            if (child.get("state") or "").upper() == "CLOSED"
            and (child.get("stateReason") or "").upper() not in ("COMPLETED", "NOT_PLANNED")
        ]
        parts = []
        if refs_not_planned:
            parts.append(
                f"{len(refs_not_planned)} child{'ren' if len(refs_not_planned) > 1 else ''} "
                f"closed as not planned ({', '.join(refs_not_planned)})"
            )
        if refs_no_reason:
            parts.append(
                f"{len(refs_no_reason)} closed with no reason recorded ({', '.join(refs_no_reason)})"
            )
        lines.append("")
        lines.append("Not counted toward completion: " + "; ".join(parts) + ".")

    previous_mix = type_counts(baseline_snapshot.get("requirements") or [])
    current_mix = type_counts(assembly["requirements"])
    if previous_mix != current_mix:
        lines.append("")
        lines.append(
            f"Requirement mix: {describe_mix(current_mix)} (previously {describe_mix(previous_mix)})."
        )

    bullets = trend_bullets(assembly, computed, previous, baseline, coverage_delta)
    if bullets:
        lines.append("")
        lines.extend(f"- {bullet}" for bullet in bullets)

    lines.append("")
    lines.append(LABEL)
    return lines


def trend_bullets(assembly, computed, previous, baseline, coverage_delta):
    diff = assembly["diff"]
    changes = diff.get("requirementChanges") or {}
    inventory = diff.get("inventoryChanges") or {}
    manifest = assembly["manifest"]
    requirements = assembly["requirements"]
    baseline_at = baseline.get("generatedAt")
    bullets = []

    classified = metrics_mod.classify_assessment_changes(
        diff.get("matchedPairs"), requirements, baseline_at
    )
    by_id = {requirement.get("id"): requirement for requirement in requirements}

    def evidence_phrase(entry):
        dated = [item for item in entry["evidence"] if item.get("at")]
        if not dated:
            return "no dated evidence is recorded for it"
        newest = max(dated, key=lambda item: util.parse_iso(item["at"]))
        return f"{newest['ref']} is dated {util.date_only(newest['at'])}"

    for entry in classified:
        requirement = by_id.get(entry["id"]) or {}
        who = f"{entry['id']} ({entry['sourceKey']})"
        if entry["cause"] == "implementation-progress":
            bullets.append(
                f"**Implementation progress.** {who} moved from {entry['from']} to {entry['to']}. "
                f"{evidence_phrase(entry)}, after the previous snapshot."
            )
        elif entry["cause"] == "newly-discovered-evidence":
            bullets.append(
                f"**Newly discovered evidence.** {who} moved from {entry['from']} to {entry['to']}, and "
                f"{evidence_phrase(entry)} {EMDASH} at or before the previous snapshot. "
                "This is evidence newly visible, not work newly done."
            )
        elif entry["cause"] == "undetermined":
            bullets.append(
                f"**Undetermined.** {who} moved from {entry['from']} to {entry['to']}, and the supporting "
                "evidence carries no usable date. Whether this is new work or newly visible work "
                "cannot be determined from the sources inspected."
            )
        else:
            bullets.append(
                f"**Assessment moved backwards.** {who} went from {entry['from']} to {entry['to']}. "
                + (requirement.get("gap") or "The cause is named in the coverage table.")
            )

    added = changes.get("added") or []
    if added:
        mix = describe_mix(type_counts(added))
        ids = ", ".join(item["id"] for item in added if item.get("id"))
        regressed = any(entry["cause"] == "regression" for entry in classified)
        sentence = (
            f"**Scope added.** {mix.capitalize()}"
            + (f" ({ids})" if ids else "")
            + f" added to {assembly['jira']['key']}."
        )
        if previous and previous["coverage"]["state"] == metrics_mod.OBSERVED:
            sentence += (
                f" The denominator rose from {previous['coverage']['denominator']} to "
                f"{computed['coverage']['denominator']}"
            )
            sentence += "." if regressed else "; no requirement lost evidence."
        like = metrics_mod.like_for_like(diff.get("matchedPairs"), requirements)
        if like and coverage_delta.get("denominatorMoved"):
            pp = util.round_half_up(like["current"]["pct"] - like["previous"]["pct"])
            sentence += (
                f" Over the {spell(like['total'])} requirements present and unchanged in both "
                f"snapshots, evidence found went from {metrics_mod.render_ratio(like['previous'])} to "
                f"{metrics_mod.render_ratio(like['current'])}, {signed_pp(pp)}."
            )
        bullets.append(sentence)

    for item in changes.get("removed") or []:
        bullets.append(
            f"**Scope removed.** {item.get('id')} ({item.get('sourceKey')}) was removed from the Jira. "
            f"It was {item.get('assessment') or 'unassessed'} at the previous snapshot."
        )
    for item in changes.get("textChanged") or []:
        bullets.append(
            f"**Text changed.** {item.get('id')} ({item.get('sourceKey')}) was edited; the previous "
            "assessment does not carry over and it was reassessed from scratch."
        )
    for item in changes.get("ambiguous") or []:
        bullets.append(
            "**Ambiguous pairing.** A requirement could not be matched to exactly one in the previous "
            "snapshot, so it is reported as a removal plus an addition rather than an edit."
        )
    if changes.get("renumbered"):
        pairs = ", ".join(
            f"{item['previousId']}{EMDASH}>{item['currentId']}" for item in changes["renumbered"][:8]
        )
        bullets.append(
            f"**Renumbering.** {pairs}. Matched on their text, not their IDs; nothing about them changed, "
            "and this is not counted among the changes."
        )

    if diff.get("mappingChanged"):
        previous_mappings = set(diff.get("previousMappings") or [])
        current_mappings = {mapping["ref"] for mapping in assembly.get("mappings") or []}
        gained = sorted(current_mappings - previous_mappings)
        lost = sorted(previous_mappings - current_mappings)
        if gained:
            bullets.append(f"**Mapping changed.** {', '.join(gained)} was added as upstream work.")
        if lost:
            bullets.append(
                f"**Mapping changed.** {', '.join(lost)} is no longer linked from "
                f"{assembly['jira']['key']}. It was the mapping at the previous snapshot and is "
                "reported here as what used to be mapped; it was not traversed this run."
            )
        if not gained and not lost:
            bullets.append(
                "**Mapping changed.** The same epics are linked, but the kind of link recorded on the "
                "Jira changed."
            )

    for ref in inventory.get("reopened") or []:
        bullets.append(f"**Reopened.** {ref} was closed at the previous snapshot and is open again.")
    for ref in inventory.get("accessRestored") or []:
        bullets.append(f"**Access changed.** {ref} is readable from this account again.")
    for ref in inventory.get("accessLost") or []:
        bullets.append(
            f"**Access changed.** {ref} could not be read this run; it was readable on "
            f"{util.date_only(baseline_at)}."
        )

    # The sentence a reader needs whenever a number fell for a reason that is
    # not the work going backwards.
    if inventory.get("accessLost") or not manifest.get("observed", bool(manifest.get("epics"))):
        bullets.append(
            f"The evidence recorded on {util.date_only(baseline_at)} has not been withdrawn. Nothing "
            "observed this run bears on the current state of the implementation; the upstream work "
            "may be complete, in flight, or unstarted."
        )

    unchanged = []
    if not added:
        unchanged.append("no requirement was added")
    if not changes.get("removed"):
        unchanged.append("no requirement was removed")
    if not changes.get("textChanged"):
        unchanged.append("no requirement's text changed")
    if not diff.get("mappingChanged"):
        unchanged.append("no mapping changed")
    if not inventory.get("reopened"):
        unchanged.append("no child issue was reopened")
    if not inventory.get("accessLost") and not inventory.get("accessRestored"):
        unchanged.append("access did not change")
    if unchanged:
        bullets.append(_join_clauses(unchanged).capitalize() + ".")

    bullets.extend(assembly.get("trendNotes") or [])
    return bullets


def _join_clauses(parts):
    if len(parts) == 1:
        return parts[0]
    return ", ".join(parts[:-1]) + ", and " + parts[-1]


# --- top level -----------------------------------------------------------


def compute_metrics(assembly):
    manifest = assembly["manifest"]
    return metrics_mod.compute(
        assembly["requirements"],
        manifest.get("children") or [],
        observed=manifest.get("observed", bool(manifest.get("epics"))),
        unobserved_reason=manifest.get("unobservedReason"),
    )


def render(assembly, tallied=None):
    computed = assembly.get("metrics") or compute_metrics(assembly)
    manifest = assembly["manifest"]
    observed = manifest.get("observed", bool(manifest.get("epics")))
    tallied = tallied or outcomes_mod.tally(assembly.get("requirements") or [])

    blocks = [header(assembly, computed)]
    # First, and in all three renderings. The paragraph is the one place the
    # position is stated rather than derived, so a rendering without it is a
    # rendering a reader has to reconstruct it from - and two readers
    # reconstruct two different positions from the same table.
    blocks.append(
        [
            "#### Overall assessment",
            "",
            summary_mod.overall_text(assembly, assembly.get("requirements") or [], tallied),
        ]
    )
    narrative = (assembly.get("summary") or "").strip()
    # An empty section with a heading over it is worse than no section: it
    # reads as a summary that said nothing rather than one nobody wrote.
    if narrative:
        blocks.append(["#### Summary", "", narrative])
    if observed:
        blocks.append(progress_section(assembly))
    else:
        blocks.append(jira_scope_section(assembly))
    blocks.append(coverage_section(assembly, computed, tallied))
    blocks.append(downstream_section(assembly))
    blocks.append(dependencies_section(assembly))
    blocks.append(scope_section(assembly))

    caveats = list(assembly.get("caveats") or [])
    coverage_buckets = computed["coverage"]["buckets"]
    if (
        computed["coverage"]["state"] == metrics_mod.OBSERVED
        and coverage_buckets["Unable to assess"] == computed["total"]
        and computed["total"] > 0
    ):
        caveats.append(
            "No requirement could be assessed; 0% reflects absent assessment, not absent "
            "implementation."
        )
    blocks.append(bullet_section("Coverage caveats", caveats))
    blocks.append(bullet_section("Risks and blockers", assembly.get("risks")))
    if not observed:
        blocks.append(needed_section(assembly))
    blocks.append(trend_section(assembly, computed))

    epics = ", ".join(mapping["ref"] for mapping in assembly.get("mappings") or [])
    if epics:
        marker = (
            f"_{MARKER} from {epics}.\nRead-only against GitHub; no Jira issues were created._"
        )
    else:
        marker = (
            f"_{MARKER}. No upstream link was found on {assembly['jira']['key']}.\n"
            "Read-only against GitHub; no Jira issues were created._"
        )
    blocks.append(["---", "", marker])

    rendered = "\n\n".join("\n".join(block).strip() for block in blocks if block)
    return rendered.rstrip() + "\n"
